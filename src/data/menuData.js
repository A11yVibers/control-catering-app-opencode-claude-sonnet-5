export function getMenuForDay(dayName) {
  return WEEKLY_MENU[dayName] || null
}

export function getAllItemsFlat() {
  return Object.entries(WEEKLY_MENU).flatMap(([day, menu]) =>
    menu.items.map((item) => ({ ...item, day, theme: menu.theme }))
  )
}

export function findItemById(itemId) {
  for (const [day, menu] of Object.entries(WEEKLY_MENU)) {
    const found = menu.items.find((item) => item.id === itemId)
    if (found) return { ...found, day, theme: menu.theme }
  }
  return null
}

export function groupByCategory(items) {
  return CATEGORY_ORDER.map((category) => ({
    category,
    label: CATEGORY_LABELS[category],
    items: items.filter((item) => item.category === category),
  }))
}

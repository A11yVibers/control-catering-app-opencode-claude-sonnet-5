/** Returns the ordered list of item ids offered on the given day-of-week (0-6). */
export function getMenuItemIdsForDay(dayOfWeek) {
  const menu = WEEKLY_MENU[dayOfWeek]
  if (!menu) return []
  return [...menu.protein, ...menu.vegetarian, ...menu.side]
}

/** Returns the full food item records offered on the given day-of-week (0-6). */
export function getMenuItemsForDay(dayOfWeek) {
  return getMenuItemIdsForDay(dayOfWeek).map((id) => FOOD_ITEMS_BY_ID[id])
}

